package aed.tp2;

class Vuelo {
    public double distancia;
    public double millasGanadas;
    public String promo;
    public double factor;

    public Vuelo(double distancia, double millasGanadas, String promo, double factor) {
        this.distancia = distancia;
        this.millasGanadas = millasGanadas;
        this.promo = promo;
        this.factor = factor;
    }
}